export const DICTS: Record<Lang, Dict> = { es, en };

let currentLang: Lang = DEFAULT_LANG;

export function setLang(lang: Lang) {
  currentLang = lang;
}

export function getLang(): Lang {
  return currentLang;
}

/** Looks up `key`, interpolating `{name}` placeholders from `vars`. Falls back
 *  to Spanish, then to the key itself, so a missing translation never renders
 *  blank. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const raw = DICTS[currentLang][key] ?? DICTS.es[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}
